"""Check that TorchCodec uses the bundled FFmpeg and can decode and encode with it.

Run with the torchcodec-ffmpeg wheel, TorchCodec and torch installed. The
assets are generated by tests/assets/generate.sh.
"""

import importlib.metadata
from pathlib import Path

import pytest
import torch
import torchcodec
from loaded_libraries import loaded_libraries
from torchcodec.decoders import AudioDecoder, VideoDecoder

import torchcodec_ffmpeg

ASSETS_DIR = Path(__file__).parent / "assets"
AUDIO_ASSETS = sorted(
    path
    for path in ASSETS_DIR.iterdir()
    if path.suffix
    in {
        ".aac",
        ".ac3",
        ".aiff",
        ".amr",
        ".au",
        ".caf",
        ".dts",
        ".eac3",
        ".m4a",
        ".mka",
        ".mp2",
        ".oga",
        ".tta",
        ".w64",
        ".wma",
        ".wv",
    }
)
VIDEO_ASSETS = sorted(
    path
    for path in ASSETS_DIR.iterdir()
    if path.suffix
    in {
        ".3gp",
        ".apng",
        ".avi",
        ".gif",
        ".mkv",
        ".mov",
        ".mxf",
        ".ogv",
        ".ts",
        ".webm",
        ".wmv",
        ".y4m",
    }
)


def test_uses_bundled_ffmpeg() -> None:
    libavcodec = {path for path in loaded_libraries() if "avcodec" in Path(path).name}
    library_dir = torchcodec_ffmpeg.LIBRARY_DIR.resolve()
    assert len(libavcodec) == 1, libavcodec
    assert Path(libavcodec.pop()).resolve().parent == library_dir
    # The package version is the FFmpeg version. TorchCodec 0.8 has no
    # ffmpeg_major_version.
    ffmpeg_major = int(importlib.metadata.version("torchcodec-ffmpeg").split(".")[0])
    if hasattr(torchcodec, "ffmpeg_major_version"):
        assert torchcodec.ffmpeg_major_version == ffmpeg_major


@pytest.mark.parametrize("path", AUDIO_ASSETS, ids=lambda path: path.name)
def test_decode_audio(path: Path) -> None:
    samples = AudioDecoder(str(path)).get_samples_played_in_range(0)
    assert samples.data.shape[-1] > 0


@pytest.mark.parametrize("path", VIDEO_ASSETS, ids=lambda path: path.name)
def test_decode_video(path: Path) -> None:
    frame = VideoDecoder(str(path))[0]
    assert frame.shape[0] == 3


def test_decode_heic() -> None:
    # decode_heic was added in TorchCodec 0.17
    decoders = pytest.importorskip("torchcodec.decoders")
    if not hasattr(decoders, "decode_heic"):
        pytest.skip("decode_heic is not available in this TorchCodec version")
    image = decoders.decode_heic(str(ASSETS_DIR / "heic.heic"))
    assert image.shape == (3, 96, 128)


@pytest.mark.parametrize(
    "name", ["out.mp4", "out.mkv", "out.webm", "out.webp", "out.gif", "out.avi"]
)
def test_encode_video(tmp_path: Path, name: str) -> None:
    # VideoEncoder was added in TorchCodec 0.9
    encoders = pytest.importorskip("torchcodec.encoders")
    if not hasattr(encoders, "VideoEncoder"):
        pytest.skip("VideoEncoder is not available in this TorchCodec version")
    frames = torch.randint(0, 255, (8, 3, 64, 64), dtype=torch.uint8)
    path = tmp_path / name
    encoders.VideoEncoder(frames, frame_rate=8).to_file(str(path))
    if path.suffix == ".webp":
        # FFmpeg cannot decode animated WebP, so check the container only
        data = path.read_bytes()
        assert data[:4] == b"RIFF" and data[8:12] == b"WEBP"
    else:
        assert len(VideoDecoder(str(path))) == 8
